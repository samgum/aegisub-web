async function showRecentSubtitles(): Promise<void> {
  const recent = await listRecentProjects();
  showShellDialog("最近字幕", (body, close) => {
    if (!recent.length) body.textContent = "暂无最近字幕。";
    for (const project of recent) {
      const button = document.createElement("button");
      button.textContent = `${project.filename} · ${new Date(project.updatedAt).toLocaleString()}`;
      button.addEventListener("click", () => {
        openDocument(project.text, project.filename, false);
        close();
      });
      body.append(button);
    }
  });
}

async function showAutosaveVersions(): Promise<void> {
  const versions = await listAutosaveVersions();
  showShellDialog("自动保存版本", (body, close) => {
    if (!versions.length) body.textContent = "暂无自动保存版本。";
    let lastFile = "";
    for (const version of versions) {
      if (version.filename !== lastFile) {
        const heading = document.createElement("strong"); heading.textContent = version.filename; body.append(heading); lastFile = version.filename;
      }
      const button = document.createElement("button");
      button.textContent = new Date(version.updatedAt).toLocaleString();
      button.addEventListener("click", () => { openDocument(version.text, version.filename, false); close(); });
      body.append(button);
    }
  });
}

function openWithCharset(): void {
  const input = document.createElement("input");
  input.type = "file";
  input.accept = fileInput.accept;
  input.addEventListener("change", async () => {
    const file = input.files?.[0];
    if (!file) return;
    const charset = prompt("字符编码（utf-8 / gb18030 / big5 / shift_jis 等）:", "utf-8") || "utf-8";
    try {
      const text = new TextDecoder(charset).decode(await file.arrayBuffer());
      openDocument(text, file.name);
      logEvent(`以 ${charset} 打开 ${file.name}`);
    } catch (error) {
      updateChrome(error instanceof Error ? error.message : String(error));
    }
  });
  input.click();
}

function runShellAegisubCommand(command: string): boolean {
  const links: Record<string, string> = {
    "help/bugs": "https://github.com/samgum/aegisub-web/issues",
    "help/contents": "https://github.com/samgum/aegisub-web#readme",
    "help/irc": "https://web.libera.chat/#aegisub",
    "help/video": "https://aegisub.org/docs/latest/visual_typesetting/",
    "help/website": "https://aegisub.org/",
  };
  if (links[command]) {
    window.open(links[command], "_blank", "noopener");
    return true;
  }
  switch (command) {
    case "app/language": {
      showShellDialog("界面语言 / Interface Language", (body, close) => {
        for (const option of languageSelect.options) {
          const control = document.createElement("button");
          control.textContent = `${option.value === languageSelect.value ? "✓ " : ""}${option.textContent ?? option.value}`;
          control.addEventListener("click", () => {
            languageSelect.value = option.value;
            languageSelect.dispatchEvent(new Event("change"));
            close();
          });
          body.append(control);
        }
      });
      return true;
    }
    case "app/log": showLog(); return true;
    case "app/new_window": window.open(location.href, "_blank", "noopener"); return true;
    case "app/options": showOptions(); return true;
    case "app/toggle/global_hotkeys": {
      const enabled = localStorage.getItem("aegisub-web.global-hotkeys") !== "true";
      localStorage.setItem("aegisub-web.global-hotkeys", String(enabled));
      updateChrome(`全局热键覆盖：${enabled ? "开" : "关"}`);
      return true;
    }
    case "app/updates": {
      void navigator.serviceWorker?.getRegistration().then(async (registration) => {
        await registration?.update();
        updateChrome("已检查更新；重新载入即可使用最新版本。");
      });
      return true;
    }
    case "app/exit": window.close(); updateChrome("浏览器不允许页面自行关闭时，请关闭当前标签页。"); return true;
    case "app/minimize": updateChrome("浏览器标签页的最小化由系统窗口管理器控制。"); return true;
    case "app/maximize": void document.documentElement.requestFullscreen?.(); return true;
    case "app/bring_to_front": window.focus(); return true;
    case "subtitle/new": newDocument(); return true;
    case "subtitle/close": newDocument(); return true;
    case "subtitle/open": fileInput.click(); return true;
    case "subtitle/open/autosave": void showAutosaveVersions(); return true;
    case "subtitle/open/charset": openWithCharset(); return true;
    case "subtitle/open/video": mediaInput.click(); return true;
    case "subtitle/save":
    case "subtitle/save/as": handle?.runCommand("save"); return true;
    case "recent/subtitle/": void showRecentSubtitles(); return true;
    case "recent/audio/":
    case "recent/video/": {
      showShellDialog("最近媒体", (body, close) => {
        if (!recentMediaFiles.length) body.textContent = "本次会话尚未打开媒体。";
        for (const file of recentMediaFiles) {
          const button = document.createElement("button");
          button.textContent = file.name;
          button.addEventListener("click", () => { handle?.loadPreviewMedia(file); close(); });
          body.append(button);
        }
      });
      return true;
    }
    case "recent/keyframes/":
    case "recent/timecodes/": updateChrome("关键帧和时间码历史由当前项目会话保存。"); return true;
    default: return false;
  }
}

function updateChrome(message?: string): void {
  filenameEl.textContent = `${dirty ? "* " : ""}${currentFilename} - Aegisub Web`;
  document.title = `${dirty ? "● " : ""}${currentFilename} — Aegisub Web`;
  if (message) statusEl.textContent = message;
  if (handle) {
    const count = handle.getDoc().cues.length;
    statusEl.textContent = message || `${currentFilename} · ${count} 行字幕 · ${handle.getDoc().format.toUpperCase()}`;
  }
}

function scheduleAutosave(): void {
  window.clearTimeout(autosaveTimer);
  autosaveEl.textContent = "正在等待自动保存…";
  autosaveTimer = window.setTimeout(async () => {
    if (!handle) return;
    await saveLastProject({ filename: currentFilename, text: handle.getText(), updatedAt: Date.now() });
    autosaveEl.textContent = `已自动保存 ${new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}`;
  }, 700);
}

function openDocument(text: string, filename: string, persist = true): void {
  documentVersion += 1;
  currentFilename = filename || "untitled.ass";
  dirty = false;

  const win = window as unknown as Record<string, unknown>;
  win.subChangeCount = 0;
  win.subSelections = [];
  if (handle) {
    handle.loadDocument({ text, filename: currentFilename });
  } else {
    editorEl.textContent = "";
    handle = createSubtitleEditor(editorEl, { text, filename: currentFilename }, {
      locale: languageSelect.value,
      spellcheck: localStorage.getItem("aegisub-web.spellcheck") !== "false",
      onAegisubCommand: runShellAegisubCommand,
      onChange: () => {
        win.subChangeCount = (win.subChangeCount as number) + 1;
        dirty = true;
        updateChrome();
        scheduleAutosave();
      },
      onSelectionChanged: (cueId) => {
        win.subSelection = cueId;
        (win.subSelections as unknown[]).push(cueId);
      },
    });
  }
  win.subHandle = handle;
  win.createSubtitleEditor = createSubtitleEditor;
  rateSelect.value = String(handle.getPlaybackRate());
  appFormatSelect.value = handle.getDoc().format;
  updateChrome();
  logEvent(`打开字幕 ${currentFilename}`);
  if (persist) scheduleAutosave();
}

async function openSubtitleFile(file: File): Promise<void> {
  try {
    const text = await file.text();
    if (/\.txt$/i.test(file.name) && !/--> |^WEBVTT|^\[Script Info\]|^\{\d+\}\{\d+\}/im.test(text)) {
      const actorSeparator = prompt("Actor separator:", localStorage.getItem("aegisub-web.text-import-actor") ?? ":") ?? ":";
      const commentStarter = prompt("Comment starter:", localStorage.getItem("aegisub-web.text-import-comment") ?? "#") ?? "#";
      const includeBlank = confirm("Include blank lines as comments?");
      localStorage.setItem("aegisub-web.text-import-actor", actorSeparator);
      localStorage.setItem("aegisub-web.text-import-comment", commentStarter);
      const doc = importPlainText(text, { actorSeparator, commentStarter, includeBlank });
      openDocument(serializeSubtitles(doc), file.name.replace(/\.txt$/i, ".ass"));
    } else openDocument(text, file.name);
  } catch (error) {
    updateChrome(error instanceof Error ? error.message : "无法读取该字幕文件");
  }
}

