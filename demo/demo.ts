function logEvent(message: string): void {
  appEvents.unshift(`${new Date().toLocaleTimeString()}  ${message}`);
  if (appEvents.length > 200) appEvents.length = 200;
}

function showShellDialog(title: string, build: (body: HTMLDivElement, close: () => void) => void): void {
  document.querySelector(".shell-dialog")?.remove();
  const dialog = document.createElement("dialog");
  dialog.className = "shell-dialog";
  const head = document.createElement("header");
  const heading = document.createElement("h2");
  heading.textContent = title;
  const closeButton = document.createElement("button");
  closeButton.textContent = "×";
  head.append(heading, closeButton);
  const body = document.createElement("div");
  body.className = "shell-dialog-body";
  const close = (): void => dialog.close();
  closeButton.addEventListener("click", close);
  build(body, close);
  dialog.append(head, body);
  dialog.addEventListener("close", () => dialog.remove());
  document.body.append(dialog);
  dialog.showModal();
}

function showOptions(): void {
  showShellDialog("Aegisub Web 设置", (body, close) => {
    const fields: [string, string, string][] = [
      ["Lead-in (ms)", "aegisub-web.lead-in", "100"],
      ["Lead-out (ms)", "aegisub-web.lead-out", "100"],
    ];
    for (const [labelText, key, fallback] of fields) {
      const label = document.createElement("label");
      label.textContent = labelText;
      const input = document.createElement("input");
      input.type = "number";
      input.value = localStorage.getItem(key) ?? fallback;
      input.addEventListener("change", () => localStorage.setItem(key, input.value));
      label.append(input);
      body.append(label);
    }
    const spell = document.createElement("label");
    const spellInput = document.createElement("input");
    spellInput.type = "checkbox";
    spellInput.checked = localStorage.getItem("aegisub-web.spellcheck") !== "false";
    spellInput.addEventListener("change", () => localStorage.setItem("aegisub-web.spellcheck", String(spellInput.checked)));
    spell.append(spellInput, document.createTextNode(" 启用浏览器拼写检查"));
    body.append(spell);
    const done = document.createElement("button");
    done.textContent = "完成";
    done.addEventListener("click", close);
    body.append(done);
  });
}

